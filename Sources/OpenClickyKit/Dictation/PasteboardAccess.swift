import AppKit
import Foundation

/// Everything on the clipboard at one moment: every item with every representation it offered.
public struct PasteboardSnapshot: Sendable, Equatable {
    public struct Representation: Sendable, Equatable {
        public var type: String
        public var data: Data

        public init(type: String, data: Data) {
            self.type = type
            self.data = data
        }
    }

    public struct Item: Sendable, Equatable {
        public var representations: [Representation]

        public init(_ representations: [Representation]) { self.representations = representations }
    }

    public var items: [Item]

    public init(items: [Item]) { self.items = items }

    public var isEmpty: Bool { items.isEmpty }
}

/// The clipboard as text insertion sees it. Production uses `NSPasteboard.general`; tests use `InMemoryPasteboard`.
public protocol PasteboardAccess: Sendable {
    /// Increments on every write, by anyone.
    var changeCount: Int { get }
    func snapshot() -> PasteboardSnapshot
    /// Puts a snapshot back exactly. Returns false if the write failed.
    @discardableResult func restore(_ snapshot: PasteboardSnapshot) -> Bool
    /// Writes text for an immediate paste, marked so clipboard managers skip it. Returns the new change count,
    /// or nil if the write failed.
    func writeTransientText(_ text: String) -> Int?
    /// Writes text the user keeps (the clipboard fallback).
    @discardableResult func writeText(_ text: String) -> Bool
}

/// Pasteboard types from nspasteboard.org that tell clipboard managers not to record an entry.
public enum PasteboardMarkers {
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    public static let plainText = "public.utf8-plain-text"
}

/// The system clipboard.
public final class SystemPasteboard: PasteboardAccess, @unchecked Sendable {
    private let pasteboard: NSPasteboard

    public init(_ pasteboard: NSPasteboard = .general) { self.pasteboard = pasteboard }

    public var changeCount: Int { pasteboard.changeCount }

    public func snapshot() -> PasteboardSnapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            PasteboardSnapshot.Item(item.types.compactMap { type in
                item.data(forType: type).map { PasteboardSnapshot.Representation(type: type.rawValue, data: $0) }
            })
        }
        return PasteboardSnapshot(items: items.filter { !$0.representations.isEmpty })
    }

    @discardableResult public func restore(_ snapshot: PasteboardSnapshot) -> Bool {
        pasteboard.clearContents()
        guard !snapshot.isEmpty else { return true }
        let items = snapshot.items.map { item -> NSPasteboardItem in
            let pasteboardItem = NSPasteboardItem()
            for representation in item.representations {
                pasteboardItem.setData(representation.data, forType: NSPasteboard.PasteboardType(representation.type))
            }
            return pasteboardItem
        }
        return pasteboard.writeObjects(items)
    }

    public func writeTransientText(_ text: String) -> Int? {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        guard item.setString(text, forType: .string) else { return nil }
        item.setData(Data(), forType: NSPasteboard.PasteboardType(PasteboardMarkers.transient))
        item.setData(Data(), forType: NSPasteboard.PasteboardType(PasteboardMarkers.autoGenerated))
        guard pasteboard.writeObjects([item]) else { return nil }
        return pasteboard.changeCount
    }

    @discardableResult public func writeText(_ text: String) -> Bool {
        pasteboard.clearContents()
        return pasteboard.setString(text, forType: .string)
    }
}

/// A clipboard in memory, for tests and dry runs. `simulateUserCopy` stands in for another app writing.
public final class InMemoryPasteboard: PasteboardAccess, @unchecked Sendable {
    private let lock = NSLock()
    private var items: [PasteboardSnapshot.Item]
    private var count = 0
    public private(set) var transientWrites: [String] = []

    public init(items: [PasteboardSnapshot.Item] = []) { self.items = items }

    public var changeCount: Int { lock.withLock { count } }

    public func snapshot() -> PasteboardSnapshot { lock.withLock { PasteboardSnapshot(items: items) } }

    @discardableResult public func restore(_ snapshot: PasteboardSnapshot) -> Bool {
        lock.withLock {
            items = snapshot.items
            count += 1
        }
        return true
    }

    public func writeTransientText(_ text: String) -> Int? {
        lock.withLock {
            items = [PasteboardSnapshot.Item([
                .init(type: PasteboardMarkers.plainText, data: Data(text.utf8)),
                .init(type: PasteboardMarkers.transient, data: Data()),
                .init(type: PasteboardMarkers.autoGenerated, data: Data()),
            ])]
            transientWrites.append(text)
            count += 1
            return count
        }
    }

    @discardableResult public func writeText(_ text: String) -> Bool {
        lock.withLock {
            items = [PasteboardSnapshot.Item([.init(type: PasteboardMarkers.plainText, data: Data(text.utf8))])]
            count += 1
        }
        return true
    }

    public func simulateUserCopy(_ text: String) { _ = writeText(text) }

    /// The plain text currently on this clipboard.
    public var string: String? {
        lock.withLock {
            items.first?.representations.first { $0.type == PasteboardMarkers.plainText }.map { String(decoding: $0.data, as: UTF8.self) }
        }
    }
}
