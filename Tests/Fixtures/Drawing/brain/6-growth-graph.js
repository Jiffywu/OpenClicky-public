step(1)
say("Linear growth adds the same amount each step; exponential growth multiplies by the same factor.")
const card = paper(240, 150, 800, 520, {title: "Linear vs exponential", board: "grid"})
const g = graph(card.x + 20, card.y + 20, card.w - 40, card.h - 40, {x: [0, 10], y: [0, 100], xLabel: "time", yLabel: "amount", grid: true})
g.plot(x => 10 * x, {tone: "blue", label: "linear: +10 each step"})
g.plot(x => 1.6 * Math.pow(2, x / 2), {tone: "orange", label: "exponential: doubles every 2 steps"})
step(2)
say("A straight line means a constant change per step.")
callout(g.at(5, 50)[0], g.at(5, 50)[1], "same increase each step", {side: "above-left"})
step(3)
say("A curve that bends upward means each step multiplies what came before.")
callout(g.at(8, 100)[0], g.at(8, 100)[1], "gets steeper and steeper", {side: "left"})
