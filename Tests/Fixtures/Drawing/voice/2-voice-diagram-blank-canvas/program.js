step(1)
say("A fridge moves heat out of its cold box using a loop of refrigerant.")
const card = paper(140, 100, 1000, 500, {title: "How a fridge keeps food cold", board: "grid"})
const comp = box(card.x + 60, card.y + 70, 220, 110, {label: "Compressor"})
const cond = box(card.x + 720, card.y + 70, 220, 110, {label: "Condenser"})
const valve = box(card.x + 720, card.y + 330, 220, 110, {label: "Expansion valve"})
const evap = box(card.x + 60, card.y + 330, 220, 110, {label: "Evaporator"})
step(2)
say("The compressor squeezes the refrigerant, making it hot and high pressure.")
arrow([comp.right + 8, comp.cy], [cond.left - 8, cond.cy], {label: "hot gas"})
step(3)
say("The condenser at the back releases that heat into your kitchen.")
text(cond.x, cond.bottom + 10, "Heat leaves here", {size: 16, tone: "red"})
step(4)
say("The refrigerant then cools as it passes through the valve.")
arrow([cond.cx, cond.bottom + 8], [valve.cx, valve.top - 8], {label: "warm liquid"})
arrow([valve.left - 8, valve.cy], [evap.right + 8, evap.cy], {label: "cold, low pressure"})
step(5)
say("Inside the fridge, the cold refrigerant soaks up heat from your food.")
region(evap.x - 10, evap.y - 10, evap.w + 20, evap.h + 20, "Cold box")
text(evap.x, evap.bottom + 14, "Food heat is absorbed here", {size: 16, tone: "sky"})
step(6)
say("The warmed vapour returns to the compressor, and the loop starts again.")
arrow([evap.cx, evap.top - 8], [comp.cx, comp.bottom + 8], {label: "cool vapour"})
